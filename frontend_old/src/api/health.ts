import { request } from './http';

// ==============================================================================
// БЛОК 1: ОПИСАНИЕ ТИПОВ
// ==============================================================================

export interface HealthResponse {
  /** Статус сервера (обычно "ok") */
  status: string;
  /** Название сервиса (например, "ConturAI") */
  service: string;
  /** Текущая версия приложения (читается из pyproject.toml) */
  version: string;
}

// ==============================================================================
// БЛОК 2: API ДЛЯ СИСТЕМНЫХ ЗАПРОСОВ
// ==============================================================================

export const healthApi = {
  /** 
   * Получает статус сервера и его текущую версию. 
   * Не требует авторизации (доступно даже на экране входа).
   * 
   * Возвращает объект вида: { status: "ok", service: "ConturAI", version: "2.1.2" }
   */
  getStatus: () => request<HealthResponse>('/status'),
};