import { request } from './http';

// ==============================================================================
// БЛОК 1: ОПИСАНИЕ ТИПОВ (TYPESCRIPT INTERFACES)
// ==============================================================================

export interface FewShotExample {
  id: string;
  question: string;
  answer: string;
}

// ==============================================================================
// БЛОК 2: API ДЛЯ РАБОТЫ С FEW-SHOT ПРИМЕРАМИ
// ==============================================================================

export const fewShotsApi = {
  /**
   * Получить список всех сохраненных примеров (пар "вопрос-ответ").
   * Доступно только администраторам.
   * 
   * Используется для отрисовки таблицы в админ-панели.
   */
  getExamples: () => request('/few-shots/get'),
  
  /**
   * Создать новый Few-Shot пример.
   * 
   * @param question - Образцовый вопрос (например, "Как оформить отпуск?").
   * @param answer - Идеальный ответ на этот вопрос, который нейросеть должна копировать по стилю.
   * 
   * Бэкенд проверит, что обе строки не пустые, и сохранит пример в БД.
   */
  createExample: (question: string, answer: string) => 
    request('/few-shots/create', {
      method: 'POST',
      body: JSON.stringify({ question, answer }),
    }),
    
  /**
   * Удалить пример по его UUID.
   * 
   * @param id - Уникальный идентификатор примера в базе данных.
   */
  deleteExample: (id: string) => 
    request(`/few-shots/${id}`, { method: 'DELETE' }),
};