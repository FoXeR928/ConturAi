import { request } from './http';

// ==============================================================================
// БЛОК 1: ОПИСАНИЕ ТИПОВ (TYPESCRIPT INTERFACES)
// ==============================================================================

// Описываем структуру одной записи из журнала аудита.
// Это полностью совпадает с тем, что возвращает наш backend в AuditLogOut.
export interface AuditLogItem {
  id: string;
  user_login: string;
  action: string;
  details: string;
  ip_address: string;
  created_at: string;
}

// Описываем структуру всего ответа от API.
// Поле total нужно для того, чтобы на фронтенде отрисовать пагинацию (количество страниц).
export interface AuditLogsResponse {
  result: boolean;
  logs: AuditLogItem[];
  total: number;
}

// ==============================================================================
// БЛОК 2: API КЛИЕНТ ДЛЯ ЖУРНАЛА АУДИТА
// ==============================================================================

export const auditApi = {
  /**
   * Получает список логов (действий пользователей) из базы данных.
   * Доступно только администраторам (на бэкенде стоит проверка).
   * 
   * @param limit - Сколько записей загружать за один раз (по умолчанию 50).
   * @param offset - Смещение для пагинации (сколько записей пропустить).
   */
  getLogs: (limit = 50, offset = 0) => 
    // Используем дженерик <AuditLogsResponse>, чтобы TypeScript знал тип возвращаемых данных.
    request<AuditLogsResponse>(`/audit/list?limit=${limit}&offset=${offset}`),
};