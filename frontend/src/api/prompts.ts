import { request } from './http';

// ==============================================================================
// БЛОК 1: ОПИСАНИЕ ТИПОВ (TYPESCRIPT INTERFACES)
// ==============================================================================

export interface PromptItem {
  key: string;           // Например: 'ai_name', 'system_prompt', 'user_prompt'
  value: string;         // Сам текст промпта
  description: string;   // Подсказка для администратора
  updated_at?: string;   // Дата последнего изменения
}

// ==============================================================================
// БЛОК 2: API ДЛЯ РАБОТЫ С ПРОМПТАМИ
// ==============================================================================

export const promptsApi = {
  /**
   * Получить список всех промптов из базы данных.
   * 
   * Доступно только администраторам.
   * Возвращает массив объектов с ключами (ai_name, system_prompt, user_prompt)
   * и их текущими текстовыми значениями, чтобы админ мог их редактировать.
   */
  getPrompts: () => request('/prompts/get'),

  /**
   * Обновить текст конкретного промпта.
   * 
   * @param key - Идентификатор промпта ('ai_name' | 'system_prompt' | 'user_prompt').
   * @param value - Новый текст промпта (поддерживает плейсхолдеры {name}, {context}, {quest}).
   * 
   * Так как промпты читаются из БД перед каждым запросом к LLM, 
   * изменения вступают в силу мгновенно, без перезапуска контейнеров.
   */
  updatePrompt: (key: string, value: string) =>
    request('/prompts/update', {
      method: 'PATCH',
      body: JSON.stringify({ key, value }),
    }),
};