import { request } from './http';

// ==============================================================================
// БЛОК 1: ОПИСАНИЕ ТИПОВ (TYPESCRIPT INTERFACES)
// ==============================================================================

export interface LlmConfigItem {
  key: string;
  value: string;
  description: string;
  input_type: 'text' | 'number' | 'float' | 'boolean';
  is_secret?: boolean;
}

// ==============================================================================
// БЛОК 2: API ДЛЯ РАБОТЫ С НАСТРОЙКАМИ LLM
// ==============================================================================

export const llmConfigsApi = {
  /**
   * Получить список всех настроек нейросети (температура, лимиты, URL vLLM).
   * 
   * Доступно только администраторам.
   * Возвращает массив объектов, каждый из которых содержит:
   * - key (например, 'vllm_temperature')
   * - value (текущее значение в виде строки)
   * - description (подсказка для админа)
   * - input_type (как отрисовывать поле на фронтенде)
   */
  getLlmConfigs: () => request('/llm-configs/get'),

  /**
   * Обновить конкретный параметр нейросети.
   * 
   * @param key - Идентификатор настройки (например, 'vllm_max_tokens').
   * @param value - Новое значение (всегда передается строкой, бэкенд сам приведет к нужному типу).
   * 
   * Благодаря тому, что параметры читаются из БД перед каждым запросом к LLM,
   * изменения вступают в силу мгновенно (перезапуск контейнеров не требуется).
   */
  updateLlmConfig: (key: string, value: string) =>
    request('/llm-configs/update', {
      method: 'PATCH',
      body: JSON.stringify({ key, value }),
    }),
};