import { ReactNode } from 'react';

// ==============================================================================
// БЛОК 1: ТИПИЗАЦИЯ И ИНТЕРФЕЙС
// ==============================================================================

export function Layout({
  sidebar,
  header,
  children,
}: {
  sidebar: ReactNode;     // Боковая панель (обычно Sidebar с чатами)
  header?: ReactNode;     // Верхняя панель (необязательная)
  children: ReactNode;    // Основной контент (например, ChatWindow или админ-панель)
}) {
  return (
    // ==========================================================================
    // БЛОК 2: ГЛАВНЫЙ КОНТЕЙНЕР (НА ВЕСЬ ЭКРАН)
    // ==========================================================================
    // h-screen — растягивает на 100% высоты окна браузера.
    // flex — включает Flexbox для разделения экрана на две части.
    // overflow-hidden — запрещает прокрутку всего окна целиком (скролл будет только внутри).
    <div className="flex h-screen bg-gray-50 overflow-hidden">
      
      {/* ========================================================================
          БЛОК 3: БОКОВАЯ ПАНЕЛЬ (SIDEBAR)
          ========================================================================
          w-64 — фиксированная ширина 256px.
          bg-gray-900 — темный фон (контрастирует с контентом).
          flex-col — элементы внутри панели выстраиваются вертикально.
          border-r — тонкая линия справа для разделения.
      */}
      <aside className="w-64 bg-gray-900 text-white flex flex-col border-r border-gray-800 shrink-0">
        {sidebar}
      </aside>

      {/* ========================================================================
          БЛОК 4: ПРАВАЯ ЧАСТЬ (ШАПКА + КОНТЕНТ)
          ========================================================================
          flex-1 — занимает всё оставшееся пространство по ширине.
          flex-col — шапка сверху, контент снизу.
      */}
      <main className="flex-1 flex flex-col min-w-0">
        
        {/* 4.1. Верхняя панель (не скроллится) */}
        {header}

        {/* 4.2. Основной контент (скроллится внутри) */}
        {/* flex-1 — заполняет оставшуюся высоту. */}
        {/* overflow-hidden — предотвращает появление двойного скроллбара. */}
        <div className="flex-1 overflow-hidden relative">
          {children}
        </div>

      </main>
    </div>
  );
}