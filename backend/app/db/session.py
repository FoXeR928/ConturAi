from collections.abc import AsyncIterator

from sqlalchemy.ext.asyncio import (
    AsyncSession,
    async_sessionmaker,
    create_async_engine,
)

from app.core.config import settings

# ==============================================================================
# БЛОК 1: СОЗДАНИЕ АСИНХРОННОГО ДВИЖКА (ENGINE)
# ==============================================================================

# Движок (Engine) — это сердце SQLAlchemy. Он управляет пулом подключений к базе данных.
# Так как мы используем асинхронный стек (FastAPI + asyncpg), мы создаем асинхронный движок.
engine = create_async_engine(
    settings.db_url,          # Строка подключения (postgresql+asyncpg://...)
    echo=settings.debug,      # Если debug=True, SQLAlchemy будет выводить все SQL-запросы в консоль (полезно для отладки)
    pool_pre_ping=True,       # Защита от "мертвых" соединений: перед выдачей соединения из пула SQLAlchemy делает быстрый пинг (SELECT 1)
)


# ==============================================================================
# БЛОК 2: ФАБРИКА СЕССИЙ (SESSION FACTORY)
# ==============================================================================

# Фабрика — это функция, которая создает новые объекты сессий (Session).
# Сама по себе фабрика ничего не подключает, она просто настраивает "шаблон" для будущих сессий.
async_session_factory = async_sessionmaker(
    engine,
    class_=AsyncSession,
    expire_on_commit=False,   # КРИТИЧЕСКИ ВАЖНО для async: после коммита объекты остаются "живыми" (не сбрасываются в detached-состояние), 
                              # что позволяет обращаться к их атрибутам без повторных запросов к БД.
)


# ==============================================================================
# БЛОК 3: ГЕНЕРАТОР СЕССИЙ ДЛЯ FASTAPI (DEPENDENCY INJECTION)
# ==============================================================================

# Эта функция используется в эндпоинтах через `session: AsyncSession = Depends(get_session)`.
# Она работает как контекстный менеджер (with):
# 1. Открывает новую сессию.
# 2. Отдает её эндпоинту (через yield).
# 3. Гарантированно закрывает её после того, как эндпоинт вернул ответ (даже если произошла ошибка).
async def get_session() -> AsyncIterator[AsyncSession]:
    async with async_session_factory() as session:
        yield session