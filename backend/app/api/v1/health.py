from fastapi import APIRouter
from app.core.config import settings, APP_VERSION

router = APIRouter()

# ==============================================================================
# БЛОК 1: ПРОВЕРКА СТАТУСА СИСТЕМЫ (HEALTHCHECK)
# ==============================================================================

@router.get("/status")
async def get_status():
    """
    Эндпоинт для проверки работоспособности бэкенда.
    
    Используется для:
    1. Docker Healthcheck (чтобы оркестратор понимал, что контейнер жив).
    2. Мониторинга (например, внешним скриптом или балансировщиком).
    3. Проверки со стороны фронтенда (если нужно понять, доступен ли сервер).
    
    Не требует авторизации (токена), так как должен быть доступен всегда.
    """
    return {
        "status": "ok",
        "service": settings.app_name,  # Берется из .env (по умолчанию "ConturAI")
        "version": APP_VERSION         # Берется из pyproject.toml при старте
    }