import os
from pathlib import Path
from cryptography.fernet import Fernet
from loguru import logger
from app.core.config import settings

# ==============================================================================
# БЛОК 1: ИНИЦИАЛИЗАЦИЯ ПУТЕЙ И БИБЛИОТЕКИ ШИФРОВАНИЯ
# ==============================================================================

# Определяем путь к файлу, где будет храниться мастер-ключ.
# Этот ключ используется для симметричного шифрования (Fernet).
MASTER_KEY_FILE = Path(settings.data_dir) / "secret" / "master.key"


# ==============================================================================
# БЛОК 2: УПРАВЛЕНИЕ МАСТЕР-КЛЮЧОМ (СОЗДАНИЕ И ЗАГРУЗКА)
# ==============================================================================

def get_master_key() -> bytes:
    """
    Читает или создает мастер-ключ для шифрования.
    
    Библиотека `cryptography` (Fernet) требует ключ в формате URL-safe base64.
    Если ключа нет (первый запуск), он генерируется и сохраняется на диск.
    """
    if MASTER_KEY_FILE.exists():
        return MASTER_KEY_FILE.read_bytes()
    
    # Генерируем новый ключ (Fernet.generate_key() делает это идеально).
    key = Fernet.generate_key()
    
    # Гарантируем, что папка secret существует
    MASTER_KEY_FILE.parent.mkdir(parents=True, exist_ok=True)
    
    # Сохраняем ключ
    MASTER_KEY_FILE.write_bytes(key)
    
    # Ограничиваем права доступа (только владелец может читать/писать).
    # Это критически важно: если злоумышленник получит этот файл, он сможет 
    # расшифровать все сохраненные в БД пароли и API-ключи.
    MASTER_KEY_FILE.chmod(0o600)
    
    logger.warning(f"Сгенерирован новый мастер-ключ шифрования: {MASTER_KEY_FILE}")
    return key


# ==============================================================================
# БЛОК 3: ГЛОБАЛЬНЫЙ ИНСТАНС ШИФРОВАЛЬЩИКА (FERNET)
# ==============================================================================

try:
    # Создаем объект Fernet. При создании он проверяет валидность ключа.
    # Этот объект (_fernet) будет использоваться во всех функциях ниже.
    _fernet = Fernet(get_master_key())
except Exception as e:
    # Если ключ поврежден или библиотека не установлена, мы не роняем всё приложение.
    # Вместо этого логируем ошибку и оставляем _fernet = None.
    logger.error(f"Ошибка инициализации Fernet: {e}")
    _fernet = None


# ==============================================================================
# БЛОК 4: ФУНКЦИИ ШИФРОВАНИЯ И ДЕШИФРОВАНИЯ
# ==============================================================================

def encrypt_secret(value: str) -> str:
    """
    Шифрует строку (например, vllm_api_key) и возвращает зашифрованный текст в base64.
    
    Если шифровальщик не инициализирован или строка пустая — возвращает исходное значение.
    """
    if not value or not _fernet:
        return value
    
    # Метод encrypt принимает байты и возвращает байты.
    # Мы кодируем строку в utf-8, шифруем, а затем декодируем результат обратно в строку,
    # чтобы сохранить его в базу данных (в колонку типа TEXT).
    return _fernet.encrypt(value.encode()).decode()


def decrypt_secret(encrypted_value: str) -> str:
    """
    Расшифровывает строку.
    
    Если текст не зашифрован (например, остался с прошлой версии приложения),
    возвращает его как есть, чтобы не ломать работу системы.
    """
    if not encrypted_value or not _fernet:
        return encrypted_value
        
    try:
        # Пытаемся расшифровать
        return _fernet.decrypt(encrypted_value.encode()).decode()
    except Exception:
        # Если расшифровать не удалось (например, это был обычный текст или старый ключ),
        # просто возвращаем исходную строку.
        # Это позволяет безопасно мигрировать со старых версий БД на новые.
        return encrypted_value