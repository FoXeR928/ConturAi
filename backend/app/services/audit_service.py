from sqlalchemy.ext.asyncio import AsyncSession
from app.db.models import AuditLog
from loguru import logger

# ==============================================================================
# БЛОК 1: ЗАПИСЬ СОБЫТИЯ В ЖУРНАЛ АУДИТА
# ==============================================================================

async def log_action(
    session: AsyncSession, 
    user_login: str, 
    action: str, 
    details: str = "", 
    ip_address: str = ""
) -> None:
    """
    Записывает действие пользователя в базу данных для последующего аудита.
    
    Параметры:
    - session: Асинхронная сессия SQLAlchemy для работы с БД.
    - user_login: Логин пользователя, совершившего действие.
    - action: Краткое название действия (например, "upload_doc", "login", "delete_user").
    - details: Дополнительные детали (например, имя загруженного файла).
    - ip_address: IP-адрес клиента (для безопасности).
    """
    try:
        # 1. Создаем объект записи аудита в памяти
        log = AuditLog(
            user_login=user_login,
            action=action,
            details=details,
            ip_address=ip_address
        )
        
        # 2. Добавляем в сессию и сохраняем в БД
        session.add(log)
        await session.commit()
        
        # 3. Дублируем важную информацию в системный лог (stdout)
        logger.info(f"AUDIT: {user_login} -> {action} | {details}")
        
    except Exception as e:
        # ======================================================================
        # БЛОК 2: ОБРАБОТКА ОШИБОК (ОТКАЗОУСТОЙЧИВОСТЬ)
        # ======================================================================
        
        # КРИТИЧЕСКИ ВАЖНО: мы НЕ выбрасываем исключение (raise) дальше.
        # Если база данных перегружена и не может записать лог, 
        # это НЕ ДОЛЖНО ломать основное действие пользователя.
        # (Например, если юзер загружает документ, и запись лога падает,
        # документ все равно должен загрузиться, а мы просто запишем ошибку в консоль).
        logger.error(f"Ошибка записи аудита: {e}")