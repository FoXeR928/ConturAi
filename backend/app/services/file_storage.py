import uuid
from pathlib import Path

from loguru import logger

from app.core.config import settings

# ==============================================================================
# БЛОК 1: ИНИЦИАЛИЗАЦИЯ ПАПКИ ДЛЯ ЗАГРУЗОК
# ==============================================================================

# Формируем абсолютный путь к папке uploads (внутри Docker это обычно /app/data/uploads).
# Папка пробрасывается наружу через volume в docker-compose, чтобы файлы не терялись при пересборке.
UPLOADS_DIR = Path(settings.data_dir).resolve() / "uploads"

# Гарантируем, что папка существует при старте приложения.
# parents=True создает все промежуточные папки, exist_ok=True не падает, если папка уже есть.
UPLOADS_DIR.mkdir(parents=True, exist_ok=True)

# Отладочный вывод: проверяем, что путь правильный и у контейнера есть права на запись.
logger.debug(f"UPLOADS_DIR = {UPLOADS_DIR}")
logger.debug(f"Writable: {__import__('os').access(UPLOADS_DIR, __import__('os').W_OK)}")


# ==============================================================================
# БЛОК 2: СОХРАНЕНИЕ ФАЙЛА НА ДИСК
# ==============================================================================

def save_original(data: bytes, original_name: str) -> str:
    """
    Сохраняет загруженный пользователем файл на диск под уникальным именем.
    
    Зачем переименовывать файл?
    1. Безопасность: предотвращает path traversal (попытки передать имя вида "../../etc/passwd").
    2. Избежание коллизий: если два пользователя загрузят файл "отчет.pdf", 
       они не перезапишут друг друга (используется UUID).
    3. Сохранение расширения: по расширению браузер при скачивании поймет, 
       как открывать файл.
       
    Возвращает сгенерированное имя файла (stored_name), которое сохраняется в БД.
    """
    # Достаем расширение (например, ".pdf"). Если расширения нет, ставим ".bin".
    ext = Path(original_name).suffix.lower() or ".bin"
    
    # Генерируем уникальное имя: 32-символьный hex-код + расширение.
    stored = f"{uuid.uuid4().hex}{ext}"
    path = UPLOADS_DIR / stored
    
    try:
        # Записываем байты на диск.
        path.write_bytes(data)
    except Exception as err:
        # Если места на диске нет или закончились права — логируем и пробрасываем ошибку,
        # чтобы транзакция в БД откатилась (файл не будет зарегистрирован).
        logger.error(f"Не удалось сохранить файл {path}: {err}")
        raise
        
    logger.info(f"Оригинал сохранён: {path} ({len(data)} байт)")
    return stored


# ==============================================================================
# БЛОК 3: ПОЛУЧЕНИЕ ПОЛНОГО ПУТИ К ФАЙЛУ
# ==============================================================================

def path_of(stored_name: str) -> Path:
    """
    Возвращает объект Path к файлу по его имени на диске (stored_name).
    Используется при скачивании, чтобы отдать файл через FileResponse.
    """
    return UPLOADS_DIR / stored_name


# ==============================================================================
# БЛОК 4: УДАЛЕНИЕ ФАЙЛА С ДИСКА
# ==============================================================================

def delete_file(stored_name: str | None) -> None:
    """
    Удаляет физический файл с диска.
    
    Проверяет, что имя файла передано (не None) и что файл действительно существует,
    чтобы избежать ошибок FileNotFoundError.
    Вызывается при удалении документа из админки.
    """
    # Если stored_name пустой (например, у документа был только введенный текст, без файла),
    # то удалять нечего.
    if not stored_name:
        return
        
    path = UPLOADS_DIR / stored_name
    if path.exists():
        path.unlink() # Метод unlink() физически удаляет файл
        logger.info(f"Файл удалён: {path}")