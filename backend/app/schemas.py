from pydantic import BaseModel
from uuid import UUID
from typing import List, Literal

# ==============================================================================
# БЛОК 1: ЧАТЫ И СООБЩЕНИЯ
# ==============================================================================

class ChatCreate(BaseModel):
    """Схема для создания нового чата."""
    name: str

class ChatRename(BaseModel):
    """Схема для переименования существующего чата."""
    name: str

class MessageIn(BaseModel):
    """
    Входящее сообщение от пользователя.
    `tags` — список тегов, по которым нужно фильтровать базу знаний RAG.
    """
    text: str
    tags: List[str] = [] 


# ==============================================================================
# БЛОК 2: ДОКУМЕНТЫ И ЗАГРУЗКИ
# ==============================================================================

class TextAdd(BaseModel):
    """
    Схема для добавления текста в RAG.
    Может использоваться двумя способами:
    1. С указанием `upload_id` (текст берется из уже загруженного файла).
    2. Без `upload_id` (просто вставляется текстом `text` с названием `name`).
    """
    name: str
    text: str
    upload_id: UUID | None = None
    tags: List[str] = []


# ==============================================================================
# БЛОК 3: ПОЛЬЗОВАТЕЛИ И БЕЗОПАСНОСТЬ
# ==============================================================================

class RegistrationUser(BaseModel):
    """
    Схема регистрации нового пользователя.
    Literal гарантирует, что роль будет строго одной из перечисленных, 
    иначе Pydantic выдаст ошибку валидации.
    """
    login: str
    user_name: str
    password: str
    role: Literal["user", "editor", "admin"] = "user" 

class UpdatePassword(BaseModel):
    """Схема смены пароля (свой или чужой, если админ)."""
    login: str
    password: str

class UpdateRole(BaseModel):
    """Схема изменения роли пользователя."""
    login: str
    role: Literal["user", "editor", "admin"]

class UpdateStatus(BaseModel):
    """Схема блокировки/разблокировки пользователя."""
    login: str
    disabled: bool


# ==============================================================================
# БЛОК 4: НАСТРОЙКИ (ПРОМПТЫ И ПАРАМЕТРЫ LLM)
# ==============================================================================

class PromptUpdate(BaseModel):
    """Схема обновления системного промпта (например, system_prompt или ai_name)."""
    key: str
    value: str

class LlmConfigUpdate(BaseModel):
    """Схема обновления динамического параметра LLM (температура, лимиты и т.д.)."""
    key: str
    value: str


# ==============================================================================
# БЛОК 5: ОБУЧЕНИЕ (FEW-SHOT)
# ==============================================================================

class FewShotCreate(BaseModel):
    """Схема добавления примера "вопрос-ответ" для улучшения качества LLM."""
    question: str
    answer: str


# ==============================================================================
# БЛОК 6: УПРАВЛЕНИЕ ДОСТУПОМ К СКАЧИВАНИЮ
# ==============================================================================

class DownloadRequestCreate(BaseModel):
    """Схема заявки на скачивание файла (от пользователя)."""
    upload_id: UUID | None = None
    chat_id: UUID | None = None


class DownloadRequestAction(BaseModel):
    """
    Схема обработки заявки (от администратора).
    Literal гарантирует, что action может быть только 'approve' или 'reject'.
    """
    request_id: UUID
    action: Literal["approve", "reject"]


# ==============================================================================
# БЛОК 7: ТЕГИ
# ==============================================================================

class TagCreate(BaseModel):
    """
    Схема создания нового тега.
    Цвет по умолчанию (синий), если админ его не указал.
    """
    name: str
    color: str = "#3b82f6"