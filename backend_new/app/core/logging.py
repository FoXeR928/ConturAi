from sys import stdout

from loguru import logger

from app.core.config import settings
from app.core.secrets import LOG_FILE

# ==============================================================================
# БЛОК 1: НАСТРОЙКА ЛОГИРОВАНИЯ (LOGURU)
# ==============================================================================

def setup_logging() -> None:
    """
    Инициализирует систему логирования с помощью библиотеки Loguru.
    Вызывается один раз при старте приложения (в функции lifespan в main.py).
    
    Loguru заменяет стандартный модуль `logging` и предоставляет:
    - Красивый вывод в консоль с цветами.
    - Встроенную ротацию логов (по размеру или времени).
    - Автоматическое сохранение логов в файл без лишних классов.
    """
    
    # Удаляем дефолтный обработчик Loguru (он пишет всё в stderr), 
    # чтобы настроить вывод под свои нужды и избежать дублирования строк.
    logger.remove()

    # ==========================================================================
    # БЛОК 2: ЗАПИСЬ ЛОГОВ В ФАЙЛ
    # ==========================================================================
    
    logger.add(
        LOG_FILE,                  # Путь к файлу (обычно data/logs/app.log)
        format="{time} | {level} | {message} | {name}", # Формат строки
        rotation="128 MB",         # Ротация: когда файл достигнет 128 МБ, создастся новый
        retention="10 days",       # Хранение: удалять файлы старше 10 дней
        level="DEBUG" if settings.debug else "INFO", # Уровень детализации
        encoding="utf-8",          # Кодировка UTF-8 (важно для русского языка)
    )

    # ==========================================================================
    # БЛОК 3: ВЫВОД ЛОГОВ В КОНСОЛЬ (STDOUT)
    # ==========================================================================
    
    # Дублируем логи в консоль (для удобства разработки и просмотра `docker logs`).
    # Если включен режим отладки (DEBUG), показываем всё вплоть до TRACE.
    # В обычном режиме (PRODUCTION) выводим только важные сообщения (WARNING, ERROR).
    logger.add(
        stdout, 
        level="TRACE" if settings.debug else "WARNING"
    )

    # ==========================================================================
    # БЛОК 4: СИСТЕМНОЕ СООБЩЕНИЕ О ЗАПУСКЕ
    # ==========================================================================
    
    # Пишем первую запись, чтобы убедиться, что логирование настроено и файл доступен.
    logger.info(f"Logging initialized → {LOG_FILE}")